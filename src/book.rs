//! # Конспект, проверенный
//!
//! Здесь показаны файлы `konspekt/*.bk`: комментарии `--` стали текстом, остальное
//! показано как код. Страницы собирает `build.rs`, поэтому новый файл в `konspekt/`
//! появляется здесь сам. В комментариях можно писать формулы LaTeX: `$x \in X$` и
//! `$$ ... $$` (см. `docs/DOCS.md`).
//!
//! Тест `tests/konspekt.rs` проверяет каждый файл и раскрывает теоремы до явных аксиом,
//! схем и силлогизма (файлы 01-03 целиком, дальше выборочно: некоторые раскрытия
//! занимают сотни тысяч строк), поэтому всё, что здесь написано, доказано по Бурбаки
//! (а не "очевидно").
//!
//! Как читать строку доказательства:
//!
//! ```text
//!   ((A ∨ A) ⇒ A) ⇒ ((A ⇒ (A ∨ A)) ⇒ (A ⇒ A))    by S4 with A := A ∨ A; B := A; C := ¬A
//!   ^ формула строки (строка номер 3)           ^ обоснование: схема S4 с подстановкой
//! ```
//!
//! Полное описание формата: `docs/FORMAT.md`.
//!
//! Пример формулы: (∃x)R есть $(\tau_x(R) \mid x) R$, а схема S5 говорит
//!
//! ```math
//! (T \mid x)\,R \Rightarrow (\exists x)\,R .
//! ```

